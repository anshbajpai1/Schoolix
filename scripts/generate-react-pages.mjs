import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

// Converts each historic document into route data consumed by React. This is a
// mechanical first migration pass: deploys no HTML page and keeps all markup,
// styles, and scripts byte-for-byte available to the React renderer.
const root = process.cwd();
const pages = [
  "index.html", "add-student.html", "additional-settings.html", "admin-dashboard.html",
  "admin-report-cards.html", "admin-signup.html", "admin-timetable.html",
  "accountant-dashboard.html", "accountant-qr-checkin.html", "accountant-attendance.html",
  "accountant-management.html", "accountant-salary.html", "school-accounts.html",
  "fees-report.html", "students.html", "teachers.html", "teacher-profile.html",
  "staff-management.html", "reports.html", "reportcards.html", "generate-tc.html",
  "passed-out-students.html", "library-dashboard.html", "library-management.html",
  "library-qr-checkin.html", "librarian-attendance.html", "notices.html", "notifications.html",
  "student-dashboard.html", "student-notices.html", "teacher-dashboard.html", "teacher-notices.html",
  "driver-dashboard.html", "vehicle-management.html", "reset-password.html", "offline.html"
];

function attributes(element) {
  return [...element.attributes].reduce((all, attribute) => ({ ...all, [attribute.name]: attribute.value }), {});
}

function pageData(html, file) {
  // Node has no DOMParser. The expressions deliberately target only document
  // shell tags; body and scripts are preserved exactly as authored.
  const title = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i)?.[1]?.trim() || "Schoolix";
  const htmlClass = html.match(/<html[^>]*\bclass=["']([^"']*)/i)?.[1] || "";
  const bodyOpen = html.match(/<body([^>]*)>/i)?.[1] || "";
  const bodyClass = bodyOpen.match(/\bclass=["']([^"']*)/i)?.[1] || "";
  const routeHref = (value) => pages.reduce((result, name) => result.replaceAll(name, `#/${name}`), value);
  const body = routeHref(html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)?.[1] || "");
  const head = html.match(/<head[^>]*>([\s\S]*?)<\/head>/i)?.[1] || "";
  const styles = [...head.matchAll(/<(style|link)\b([\s\S]*?)(?:>([\s\S]*?)<\/style>|\/?>)/gi)]
    .filter((match) => match[1].toLowerCase() === "style" || /\brel=["']stylesheet["']/i.test(match[2]))
    .map((match) => ({ tag: match[1].toLowerCase(), attributes: Object.fromEntries([...match[2].matchAll(/([\w-]+)=["']([^"']*)["']/g)].map((item) => [item[1], item[2]])), text: match[3] || "" }));
  const scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].map((match) => ({
    attributes: Object.fromEntries([...match[1].matchAll(/([\w-]+)=["']([^"']*)["']/g)].map((item) => [item[1], item[2]])),
    text: routeHref(match[2])
  }));
  return { file, title, htmlClass, bodyClass, body, styles, scripts };
}

const destination = path.join(root, "react-src", "generated");
const pagesDestination = path.join(destination, "pages");
await rm(pagesDestination, { recursive: true, force: true });
await mkdir(pagesDestination, { recursive: true });
await mkdir(destination, { recursive: true });

const loaders = [];
for (const page of pages) {
  const data = pageData(await readFile(path.join(root, page), "utf8"), page);
  const moduleName = page.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase();
  await writeFile(path.join(pagesDestination, `${moduleName}.js`), `export default ${JSON.stringify(data)};\n`);
  loaders.push(`${JSON.stringify(page)}: () => import("./pages/${moduleName}.js").then((module) => module.default)`);
}

await writeFile(
  path.join(destination, "pages.js"),
  `// Generated by scripts/generate-react-pages.mjs. Do not edit manually.\nexport const pageLoaders = {\n  ${loaders.join(",\n  ")}\n};\nexport const pageNames = new Set(Object.keys(pageLoaders));\n`
);
console.log(`Generated ${pages.length} lazy React route modules`);
